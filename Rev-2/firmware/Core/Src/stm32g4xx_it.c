/* 74HC174 needs roughly 20ns of clock pulse width and 25ns of output propagation
   at 3.3V, and the latch outputs additionally go through series resistors. One
   NOP is 5.95ns at 168MHz, so eight of them give ~48ns of margin per phase.
   Rev-1 got away with a single NOP only because it ran at 48MHz. */
#define LATCH_SETTLE()  do { \
    __NOP(); __NOP(); __NOP(); __NOP(); \
    __NOP(); __NOP(); __NOP(); __NOP(); \
  } while (0)
