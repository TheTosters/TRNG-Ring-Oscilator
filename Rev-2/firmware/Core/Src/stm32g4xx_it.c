/**
  * @brief This function handles TIM6 global and DAC1 channel underrun error interrupts.
  */
void TIM6_DAC_IRQHandler(void)
{
  /* USER CODE BEGIN TIM6_DAC_IRQn 0 */
  TIM6->SR = 0;	//should be first DO NOT CHANGE

  //Both latches are clocked together, but they sit on different ports so this
  //cannot be one register write. The two groups end up one store apart (~6ns),
  //which is irrelevant - they are independent noise sources.
  //latch down
  GPIOB->BRR = latch_a_Pin;
  GPIOA->BRR = latch_b_Pin;
  LATCH_SETTLE();

  //latch up - the rising edge on CP is what samples both 74HC174
  GPIOB->BSRR = latch_a_Pin;
  GPIOA->BSRR = latch_b_Pin;
  LATCH_SETTLE();

  //get latched data - all eight ring outputs are on port A, see ro_port_bit[]
  collectEntropyBits(GPIOA->IDR);

  /* USER CODE END TIM6_DAC_IRQn 0 */
  HAL_TIM_IRQHandler(&htim6);
  /* USER CODE BEGIN TIM6_DAC_IRQn 1 */

  /* USER CODE END TIM6_DAC_IRQn 1 */
}

